const word = (value: number, lo: number, hi: number, low: string, mid: string, high: string) => value < lo ? low : value > hi ? high : mid;

/** 点数が、どの数値から決まったかを一行で。 */
export function areaReason(id: AreaId, p: { moon: number; comp: number; day: number }, force: { go: number; change: number }) {
  if (id === 'work') return '決め手：自分で進む力は' + word(force.go, .4, .6, '控えめ', 'ふつう', '強め') + 'です。';
  if (id === 'love') return '決め手：周りへの働きかけは' + word(force.change, .45, .65, '控えめ', 'ふつう', '強め') + '、月は' + word(p.moon, -.7, .7, '向かい風', '穏やか', '追い風') + 'です。';
  if (id === 'money') return '決め手：今日の五行とあなたの相性は' + word(p.comp, -.7, .7, 'かみ合いにくく、守りが向きます。', 'ふつうで、堅実に進めます。', 'よくかみ合い、お金の判断が冴えます。');
  const balance = Math.abs(force.go - force.change) < 0.3 ? '力のつり合いも取れています。' : '力に偏りがあるので、無理は禁物です。';
  return '決め手：日の波は' + word(p.day, -1.2, 1.2, '下り坂', '横ばい', '上り坂') + '、' + balance;
}
