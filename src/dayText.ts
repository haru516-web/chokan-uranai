/** その人のタイプ（季節×深さ×「−」×A）だけで決まる一文。季節4×深さ10の持ち味・弱みが、今日の段階に合わせて出る。 */
function typeLine(t: RankRow['t'], level: number) {
  const [, , strength, weakness] = content.depths[t.ni];
  const name = SEASON[t.mod].n + 'の' + DEPTH_NAMES[t.ni < 3 ? 0 : t.ni < 5 ? 1 : t.ni < 7 ? 2 : 3] + '（' + t.num.toFixed(1) + (t.minus ? '・−' : '') + (t.A ? '・A' : '') + '）のあなたは、';
  const body = level <= 1 ? '「' + strength + '」で持ち味が出やすい日です。'
    : level === 2 ? '「' + strength + '」を活かしつつ、「' + weakness + '」には気をつけて。'
    : '「' + weakness + '」が顔を出しやすい日。意識して、無理を減らしましょう。';
  const extra = (t.minus ? '「−」の型は、早めの休息が味方になります。' : '') + (t.A ? 'Aの型は、振れ幅が大きい日になりやすいです。' : '');
  return name + SEASON[t.mod].act + '季節の型。' + body + extra;
}

