/** 日付で文の候補を順に回す。同じ名札・同じ日なら必ず同じ文になり、日が変われば別の文になる。 */
export const rotate = <T,>(pool: T[], dayIndex: number, shift = 0): T => pool[(((dayIndex + shift) % pool.length) + pool.length) % pool.length];
/** その日の4分野の点数から、いちばん良い分野で何をするか・気をつけたい分野で何を避けるかを、実際の行動で書く。 */
function practicalText(row: RankRow, force: { go: number; change: number }, dayIndex: number): { text: string; marks: Mark[] } {
  const scores = areaScores(row, force);
  const best = scores.reduce((top, item) => item.point > top.point ? item : top, scores[0]);
  const worst = scores.reduce((low, item) => item.point < low.point ? item : low, scores[0]);
  const index = scores.indexOf(best);
  const mark = (id: AreaId): Mark => ({ text: AREA_META[id].label, color: AREA_META[id].color });
  const withCaution = (text: string, caution: boolean, shift: number) => caution
    ? { text: text + rotate(PRACTICAL_CAUTION[worst.id], dayIndex, shift), marks: [mark(best.id), mark(worst.id)] }
    : { text, marks: [mark(best.id)] };
  if (best.stars >= 4) return withCaution(rotate(PRACTICAL_TOP[best.id], dayIndex, index), worst.stars <= 2 && worst.id !== best.id, index);
  if (best.stars === 3) return withCaution(rotate(PRACTICAL_FINE[best.id], dayIndex, index), worst.stars <= 2 && worst.id !== best.id, index);
  // どの分野も控えめな日。いちばん無理がきく分野の一手＋やめておくこと（別の分野）。
  return withCaution(rotate(PRACTICAL_SAFE[best.id], dayIndex, index), worst.id !== best.id, index + 1);
}
const FACTOR_ORDER: FactorId[] = ['base', 'moon', 'depth', 'aff', 'comp', 'day', 'vor', 'hw'];

const GO = ['自分で前へ進む力は、ほとんど出ない日です。', '自分で進む力は控えめです。', '自分で進む力は、ふつうに出ます。', '自分で進む力は、しっかり出ます。', '自分で進む力は、今日は特に強く出ます。'];
const CHANGE = ['周りを動かすのは難しい日です。', '周りへの働きかけは控えめです。', '頼みごとや提案は、ふつうに届きます。', '頼みごとや提案が、よく届きます。', '人を巻き込む力が、今日は特に強く出ます。'];
const band = (value: number, edges: number[]) => edges.filter(edge => value >= edge).length;
const GO_EDGES = [0.25, 0.42, 0.58, 0.72];
const CHANGE_EDGES = [0.35, 0.5, 0.65, 0.78];

export type Basis = { id: FactorId; label: string; points: number; impact: number };

export function outlookText(row: RankRow, force: { go: number; change: number }, context: SeaContext) {
  const { p, t } = row;
  // 日付に名札の番号を足して候補を選ぶ。同じ日・同じ段階でも、タイプが違えば別の文になる。
  const dayIndex = context.dayIndex + t.key * 7;
  const season = SEASON[t.mod];
  const raw: [FactorId, number][] = [
    ['base', p.base - 5.5], ['moon', p.moon], ['depth', p.depth], ['aff', p.aff], ['comp', p.comp], ['day', p.day],
    ...(t.A ? [['vor', p.vor] as [FactorId, number]] : []),
    ...(t.minus ? [['hw', p.hw] as [FactorId, number]] : []),
  ];
  const basis: Basis[] = raw
    .map(([id, points]) => ({ id, label: FACTOR_LABELS[id], points, impact: Math.max(-1, Math.min(1, points / SCALE[id])) }))
    .filter(item => Math.abs(item.impact) >= MINOR)
    .sort((a, b) => Math.abs(b.impact) - Math.abs(a.impact));
  const say = (item: Basis) => PHRASES[item.id][item.impact > 0 ? 'up' : 'down'](season.n, season.moon);
  const ups = basis.filter(item => item.impact > 0);
  const downs = basis.filter(item => item.impact < 0);
  // 「−」の向かい風は毎日同じ強さでかかる固定の補正なので、その日の主役にはしない（ほかに何もないときだけ主役にする）。
  // 月の形など動きの遅い項目がずっと主役になって毎日同じ説明にならないよう、目立つ項目の上位3つを日付で順に主役にする。
  const leads = basis.filter(item => item.id !== 'hw').slice(0, 3);
  const lead = leads.length ? rotate(leads, dayIndex) : basis[0];
  const others = basis.filter(item => item !== lead && Math.abs(item.impact) >= 0.2).slice(0, 3);
  const second = others.length ? rotate(others, dayIndex, 1) : undefined;
  const { level, sub } = tierPosition(row.rank);

  // ひと言＝段階のひと言＋実際にどうするか（4分野の点数から）。星の理由（月や五行）は、詳細の「追い風・向かい風」に書いてある。
  const practical = practicalText(row, force, dayIndex);
  const line = rotate(VERDICT[level][sub], dayIndex) + practical.text;
  // 書き出しは今日の月・潮・日の干支。毎日変わるので、順位が同じ日が続いても同じ文にならない。
  const stage = DAY_STAGES[p.dpos];
  const detail = '今日は' + context.moon + '、' + context.phaseTide + '。' + dayNote(context)
    + '日の海は「' + stage.n + '」で、' + stage.d + '。'
    + typeLine(t, level)
    + (ups.length ? '追い風になっているのは、' + ups.slice(0, 2).map(say).join('こと、') + 'ことです。' : '目立つ追い風は見当たりません。')
    + (downs.length ? '向かい風になっているのは、' + downs.slice(0, 2).map(say).join('こと、') + 'ことです。' : '目立つ向かい風はありません。')
    + GO[band(force.go, GO_EDGES)] + CHANGE[band(force.change, CHANGE_EDGES)];
  const main = lead ? rotate(ACTIONS[lead.id][lead.impact > 0 ? 'up' : 'down'][force.go >= 0.5 ? 0 : 1], dayIndex, FACTOR_ORDER.indexOf(lead.id))
    : force.go >= 0.5 ? '今日は大きな差のない日。いつもの用事を、いつもの順で進める。' : '今日は大きな差のない日。手元を整えて、早めに休む。';
  // 添える一言は、日替わりで「二番目の理由からの一言」と「今日の日の海（12日で一巡）の一手」を交互にする。
  const tail = second && dayIndex % 2 === 0 ? SIDE[second.id][second.impact > 0 ? 'up' : 'down'] : DAY_WAVE[p.dpos].act;
  const action = main + 'あわせて、' + tail;
  // marks：ひと言の中で色を付ける言葉（分野名）。画面・打ち出し・共有画像で使う。
  return { line, marks: practical.marks, detail, action, basis };
}
